import { format } from 'date-fns'
import type { Category, PaymentSource, Transaction } from './types'
import { byCategory, expenses, income, sum } from './analytics'

// Built-in PDF fonts have no ₹ glyph, so amounts use "Rs" with Indian grouping.
const n2 = new Intl.NumberFormat('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
const rs = (n: number) => `Rs ${n2.format(n)}`

export interface StatementInfo { name: string; email: string | null; from: Date; to: Date; filterNote: string }

/** A statement of exactly the transactions passed in (the caller applies filters). jsPDF is lazy-loaded. */
export async function buildStatementPdf(ts: Transaction[], cats: Category[], sources: PaymentSource[], info: StatementInfo): Promise<Blob> {
  const { jsPDF } = await import('jspdf')
  const autoTable = (await import('jspdf-autotable')).default
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const W = doc.internal.pageSize.getWidth()
  const teal: [number, number, number] = [15, 118, 110]
  const catName = (id: string | null) => cats.find((c) => c.id === id)?.name ?? 'Uncategorised'
  const srcName = (id: string | null) => sources.find((s) => s.id === id)?.displayName ?? ''

  doc.setFillColor(...teal); doc.rect(0, 0, W, 78, 'F')
  doc.setTextColor(255); doc.setFont('helvetica', 'bold'); doc.setFontSize(20); doc.text('SpendWise statement', 40, 44)
  doc.setFont('helvetica', 'normal'); doc.setFontSize(10)
  doc.text(`${format(info.from, 'd MMM yyyy')} - ${format(info.to, 'd MMM yyyy')}`, 40, 62)
  doc.text([info.name || '', info.email ?? ''].filter(Boolean).join('  |  '), W - 40, 62, { align: 'right' })

  const spent = sum(expenses(ts)); const inc = sum(income(ts)); const excluded = ts.filter((t) => t.excludeFromReports).length
  doc.setTextColor(30); doc.setFontSize(10)
  const boxes: Array<[string, string]> = [['Spent', rs(spent)], ['Income', rs(inc)], ['Net', rs(inc - spent)], ['Transactions', String(ts.length)]]
  const bw = (W - 80 - 30) / 4
  boxes.forEach(([k, v], i) => {
    const x = 40 + i * (bw + 10)
    doc.setDrawColor(220); doc.roundedRect(x, 96, bw, 48, 6, 6)
    doc.setTextColor(110); doc.setFontSize(8.5); doc.text(k, x + 10, 113)
    doc.setTextColor(20); doc.setFontSize(12); doc.setFont('helvetica', 'bold'); doc.text(v, x + 10, 133); doc.setFont('helvetica', 'normal')
  })
  doc.setFontSize(8.5); doc.setTextColor(110)
  doc.text(doc.splitTextToSize(`${info.filterNote}${excluded ? ' Rows marked * are excluded from reports.' : ''}`, W - 80), 40, 162)

  const cats_ = [...byCategory(ts).entries()].sort((a, b) => b[1] - a[1])
  autoTable(doc, {
    startY: 182, head: [['Category', 'Spent', 'Share']], theme: 'striped', headStyles: { fillColor: teal }, styles: { fontSize: 9 },
    columnStyles: { 1: { halign: 'right' }, 2: { halign: 'right' } }, margin: { left: 40, right: 40 },
    body: cats_.length ? cats_.map(([id, v]) => [catName(id), rs(v), spent ? `${Math.round((v / spent) * 100)}%` : '-']) : [['No expenses in this period', '', '']],
  })

  const rows = [...ts].sort((a, b) => a.occurredAt.localeCompare(b.occurredAt)).map((t) => [
    format(new Date(t.occurredAt), 'dd MMM yyyy, HH:mm'), t.merchantName + (t.excludeFromReports ? ' *' : ''),
    t.splits.length ? 'Split' : catName(t.categoryId), srcName(t.paymentSourceId) || t.paymentMethod.toUpperCase().replace('_', ' '),
    (t.type === 'credit' ? '+ ' : '- ') + rs(t.amount),
  ])
  autoTable(doc, {
    startY: ((doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY) + 20,
    head: [['Date', 'Merchant', 'Category', 'Paid via', 'Amount']], theme: 'grid', headStyles: { fillColor: teal }, styles: { fontSize: 8.5, cellPadding: 4 },
    columnStyles: { 4: { halign: 'right', cellWidth: 90 }, 0: { cellWidth: 92 } }, margin: { left: 40, right: 40 },
    body: rows.length ? rows : [['', 'No transactions', '', '', '']],
    didDrawPage: () => {
      const H = doc.internal.pageSize.getHeight()
      doc.setFontSize(8); doc.setTextColor(140)
      doc.text(`Generated by SpendWise on ${format(new Date(), 'd MMM yyyy, h:mm a')} from your recorded transactions.`, 40, H - 24)
      doc.text(`Page ${doc.getNumberOfPages()}`, W - 40, H - 24, { align: 'right' })
    },
  })
  return doc.output('blob')
}
